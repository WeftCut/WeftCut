// The side-panel view's one HTML document, made from the companion UI's plain
// ES modules (`cli/companion/panel/panel.js` and what it imports from `ui/`):
// the script bundled and the stylesheet inlined, so the document needs
// nothing else. An MCP Apps view's default CSP refuses every request, the
// view's own files included (docs/adr/0186).
import { readFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const ROOT = path.resolve(fileURLToPath(new URL('..', import.meta.url))) // apps/desktop
const COMPANION = path.join(ROOT, 'cli', 'companion')

/** Where the generated document is committed: both servers embed it from here. */
export const PANEL_HTML = path.join(COMPANION, 'panel', 'panel.html')

const HEADER = '<!-- Generated by apps/desktop/scripts/build-side-panel.mjs from cli/companion/panel/ and cli/companion/ui/. Do not edit: run `node scripts/build-side-panel.mjs`. -->'

/** The document, as it is to be committed. */
export async function renderPanelHtml() {
  const bundled = await build({
    entryPoints: [path.join(COMPANION, 'panel', 'panel.js')],
    // LANDMINE: esbuild names each module in a comment relative to this
    // directory; left to the process's cwd, a run from elsewhere would make
    // other bytes, and with them another view address.
    absWorkingDir: ROOT,
    bundle: true,
    write: false,
    format: 'iife',
    target: 'es2022',
    charset: 'utf8',
    legalComments: 'none',
    loader: { '.svg': 'dataurl' },
    logLevel: 'silent',
  })
  // LANDMINE: a `</script` inside the script would end the element early.
  const script = bundled.outputFiles[0].text.replaceAll('</script', '<\\/script')
  const style = readFileSync(path.join(COMPANION, 'ui', 'app.css'), 'utf8').replaceAll('</style', '<\\/style')
  return [
    '<!doctype html>',
    HEADER,
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    '<title>WeftCut</title>',
    `<style>\n${style.trimEnd()}\n</style>`,
    '</head>',
    '<body>',
    '<main id="companion"></main>',
    `<script>\n${script.trimEnd()}\n</script>`,
    '</body>',
    '</html>',
    '',
  ].join('\n')
}
